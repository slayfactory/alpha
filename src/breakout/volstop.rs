//! TK-676 (§13.74): расстояние стопа от волатильности — один раз на входе, целые тысячные процента цены входа.
//!
//! `V` — волатильность в процентах цены (NATR или реализованная, закрытая минутка `t−1`); форма `vf`: 1 `a·V`, 2 `b + a·V`, 3 `a·V^p`, 4 `a·ln(1 + V/v0)`;
//! режимный множитель `(V_z / V)^ρ` умножает `V` (`vz`, `vr`). Итог зажат в `[vm, s]`: верхняя граница главнее нижней (при `s < vm` расстояние — `s`).
//! Арифметика с плавающей точкой — только в расчёте этого параметра (раз на сделку, не на событие ленты); результат округляется до 0,001 % и дальше
//! цена стопа — целочисленная (`frac`), как у прочих стопов.

use super::params::ExitCfg;

/// Расстояние стопа `d`, тысячные процента цены входа; `None` — стопа от волатильности нет (`vf = 0`) или нет значения источника (остаётся жёсткий `s`).
/// `vol_e8`, `volz_e8` — `V` и `V_z` как доля цены ×1e8 (−1 — нет значения).
pub fn stop_pm(ex: &ExitCfg, vol_e8: i64, volz_e8: i64) -> Option<i64> {
    if ex.vf == 0 || vol_e8 < 0 {
        return None;
    }
    let mut v = vol_e8 as f64 / 1e6;
    if ex.vz != 0 {
        if volz_e8 < 0 {
            return None;
        }
        if v > 0.0 {
            v *= (volz_e8 as f64 / 1e6 / v).powf(ex.vr_m as f64 / 1000.0);
        }
    }
    let a = ex.va_m as f64 / 1000.0;
    let d = match ex.vf {
        1 => a * v,
        2 => ex.vb_pm as f64 / 1000.0 + a * v,
        3 => a * v.powf(ex.vp_m as f64 / 1000.0),
        4 => a * (1.0 + v / (ex.v0_pm as f64 / 1000.0)).ln(),
        _ => return None,
    };
    if d.is_nan() {
        return None;
    }
    let pm = (d * 1000.0).round().clamp(0.0, 1e9) as i64;
    Some(pm.max(ex.vm_pm).min(ex.s_pm))
}
