//! Записи касаний и подходов, кольцо съеденного, слот фронтран-замера и их помощники.

use super::*;

/// Запись касания живого уровня (таск 35, В-42): уровень стал лучшей ценой
/// своей стороны и перестал ею быть — или умер, не перестав. Правила — в
/// документации модуля («Касания»). Уровень при этом жив и в `LevelRecord`
/// не попадает ничем — поэтому запись отдельная.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TouchRecord {
    /// Сторона книги.
    pub side: Side,
    /// Цена в тиках.
    pub price_tick: i64,
    /// Порядковый номер касания у этого уровня: 0, 1, 2…
    pub touch_index: u32,
    /// Кадр начала касания, мс.
    pub start_ms: i64,
    /// Кадр конца касания (уход с лучшей цены или смерть), мс.
    pub end_ms: i64,
    /// `end_ms − start_ms`.
    pub duration_ms: i64,
    /// Кадр рождения уровня, мс: возраст на момент касания —
    /// `start_ms − level_birth_ms`.
    pub level_birth_ms: i64,
    /// Размер в лотах в кадре начала.
    pub size_at_touch: i64,
    /// Максимум размера до кадра начала.
    pub size_max_before: i64,
    /// Объём сделок против уровня в лотах за касание.
    pub traded_during: i64,
    /// Сумма лотов той же стороны строго лучше уровня по цене на кадре за
    /// секунду до касания (В-45; документация модуля, «Касания»: кадр в
    /// 1–2 с до касания, никогда позже секунды до него).
    pub frontrun_lots: i64,
    /// Цена **первого фронтранера** в том же наблюдении, что `frontrun_lots`
    /// (B2, 2026-09-17): ближайший к уровню уровень той же стороны строго
    /// лучше него с ненулевым размером. `None` — впереди уровня ничего не
    /// стояло; вход тогда берётся как раньше (`P ± 1` тик). Спека отскока §2:
    /// «заходят либо в упор, либо от фронтрана» [D 02:35].
    pub frontrun_tick: Option<i64>,
    /// Та же сумма на последнем кадре до касания — сметено последним шагом
    /// цены (прежний `frontrun_lots` до В-45).
    pub swept_lots: i64,
    /// Число нулей в конце `price_tick` в десятичной записи: 0/1/2/3+.
    pub round_zeros: u8,
    /// Касание кончилось смертью уровня, а не уходом с лучшей цены.
    pub ended_by_death: bool,
    /// Живых уровней той же стороны с размером не ниже `H3` после кадра
    /// начала не дальше `DISTANCE_MAX_BPS` от цены уровня (включая сам
    /// уровень; В-45).
    pub stack_levels: u32,
    /// Цена (тик) ближайшей живой плотности той же стороны **за** уровнем
    /// (для бида — ниже) в том же окне и по тому же правилу, что `stack_levels`
    /// — «вторая плотность завала»: стоп практиков «за первую-вторую
    /// плотность» [D 13:41] ставится за неё (E6 базы, В-64). `None` — за
    /// уровнем в окне никого.
    pub stack_next_tick: Option<i64>,
    /// Объём сделок против уровня за первые 1 / 2 / 3 с касания (лоты;
    /// `REACTION_WINDOWS_S`), окно реакции практиков: агрессия сразу после
    /// касания → пробой, тишина → отскок [K 44:53; N 1:27:16] (E4 базы). Если
    /// касание кончилось раньше окна — объём до конца касания (см.
    /// `duration_ms`).
    pub traded_first_s: [i64; REACTION_WINDOWS_S.len()],
    /// Оборот инструмента за последний час к старту касания (лоты, все
    /// неблочные сделки обеих сторон; `FLOW_WINDOW_MIN`) — знаменатель силы
    /// «×поток» (идея 8 транскрипций [P 06:25; N 1:20:13; Z 35:29]; так же
    /// считает «силу» сторонний DensityBounceGuard: объём плотности / оборот
    /// за час): `strength_flow = size_at_touch / flow_1h_lots`.
    pub flow_1h_lots: i64,
    /// Сила «×соседи» на кадре старта касания для окон `STRENGTH_WINDOWS_BPS`,
    /// проценты × 100; `-1` — соседей в окне не было (ось исследования порога
    /// В-61, 2026-09-18).
    pub strength_e2: [i64; STRENGTH_WINDOWS_BPS.len()],
    /// История силы: минимум силы «×соседи» (±20 bps) за последние `T` с из
    /// `STRENGTH_HELD_WINDOWS_S` по выборкам раз в секунду; `-1` — уровень
    /// моложе `T` или сила в окне не определена.
    pub strength_held_e2: [i64; STRENGTH_HELD_WINDOWS_S.len()],
    /// Сколько раз уровень уже рождался на этой цене и стороне за окно
    /// `repeat_window_ms` до **рождения** этого уровня (мерцание/«пружинка»):
    /// тот же `repeat_count`, что у смерти, — считается при рождении, не на
    /// касании. Пока уровень жив, других рождений на его цене не бывает.
    pub repeat_count: u32,
    /// Направленная глубина (T2, П-02, открывает Г-07): сумма размеров той
    /// же стороны книги строго **дальше от середины**, чем уровень, на кадре
    /// начала касания — не симметричное окно `DISTANCE_MAX_BPS`/
    /// `STRENGTH_WINDOWS_BPS`, а весь остаток кадра позади уровня (`Book::
    /// levels` идёт от лучшей цены вглубь, В-45: сумма размеров наблюдений
    /// строго дальше индекса уровня). Точность зависит от глубины исходной
    /// записи: на `.200` (В-106) кадр несёт до 200 наблюдений на сторону, на
    /// обычной `.50` — не больше 50, поэтому число на `.50` — грубый прокси,
    /// не то же самое значение, что дал бы `.200`.
    pub depth_behind_lots: i64,
}

impl TouchRecord {
    /// Возраст уровня на момент касания, мс.
    pub fn age_ms(&self) -> i64 {
        self.start_ms - self.level_birth_ms
    }
}

/// Чем кончился **подход** — взведённое заранее состояние уровня, когда цена
/// другой стороны подошла к нему на полосу `approach_bps` (F1 этапа F, В-73:
/// лимитка ставится на подходе и стоит, пока стена жива).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ApproachEnd {
    /// Цена дошла до уровня: касание началось (`touch_start_ms` заполнен).
    Touch,
    /// Уровень умер, не дождавшись цены.
    LevelDeath,
    /// Лучшая цена другой стороны ушла дальше `2 × approach_bps`.
    PriceLeft,
}

impl ApproachEnd {
    /// Имя для CSV и тестов.
    pub fn name(self) -> &'static str {
        match self {
            ApproachEnd::Touch => "touch",
            ApproachEnd::LevelDeath => "level_death",
            ApproachEnd::PriceLeft => "price_left",
        }
    }

    /// Обратно к `name` — для чтения CSV.
    pub fn parse(s: &str) -> Option<Self> {
        match s {
            "touch" => Some(ApproachEnd::Touch),
            "level_death" => Some(ApproachEnd::LevelDeath),
            "price_left" => Some(ApproachEnd::PriceLeft),
            _ => None,
        }
    }
}

/// Запись подхода живого уровня к цене (F1 этапа F): момент, когда лучшая
/// цена **другой** стороны впервые вошла в полосу `D` bps от уровня, живой
/// уровень при этом держал порог В-66 и был не лучшим (то есть цена ещё не
/// дошла). Запись эмитится **на снятии**: касанием, смертью уровня или
/// уходом цены за `2 × D` (гистерезис). Поля, кроме `disarm_*`, — состояние
/// кадра взвода; уровень жив и в `LevelRecord` не попадает ничем.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ApproachRecord {
    /// Сторона книги — сторона уровня (вход ставится за неё).
    pub side: Side,
    /// Цена уровня в тиках.
    pub price_tick: i64,
    /// Порядковый номер подхода у этого уровня: 0, 1, 2… (растёт как
    /// `touch_index`, включая подходы уровней прогрева — те не эмитируются).
    pub approach_index: u32,
    /// Кадр взвода, мс.
    pub arm_ms: i64,
    /// Расстояние от уровня до лучшей цены другой стороны в кадре взвода,
    /// bps по цене уровня (тот же расчёт, что `dist_bps` ёмкости).
    pub arm_dist_bps: i64,
    /// Кадр рождения уровня, мс: возраст на взводе — `arm_ms − level_birth_ms`.
    pub level_birth_ms: i64,
    /// Размер уровня в лотах в кадре взвода.
    pub size_at_arm: i64,
    /// Лучшая цена **своей** стороны в кадре взвода (у бид-стены — лучший
    /// бид, он выше цены стены: цена к стене ещё не дошла).
    pub best_own_tick: i64,
    /// Лучшая цена **другой** стороны на её последнем кадре к моменту взвода
    /// (у бид-стены — лучший аск) — от неё считается полоса.
    pub best_opp_tick: i64,
    /// Оборот инструмента за последний час к взводу, лоты (как у касания).
    pub flow_1h_lots: i64,
    /// Сила «×соседи» на кадре взвода для окон `STRENGTH_WINDOWS_BPS`,
    /// проценты × 100; `-1` — соседей в окне не было (как у касания).
    pub strength_e2: [i64; STRENGTH_WINDOWS_BPS.len()],
    /// Направленная глубина на кадре взвода (см. `TouchRecord::depth_behind_lots`,
    /// T2 П-02): та же сумма, тот же прокси на `.50` против `.200`.
    pub depth_behind_lots: i64,
    /// «Завал» на кадре взвода (T-28, Г-28 П-02 на подходе): то же правило, что
    /// `TouchRecord::stack_levels` (живые уровни той же стороны не ниже `H3` не
    /// дальше `DISTANCE_MAX_BPS`, включая сам уровень, после свипа кадра), но на
    /// кадре взвода, а не старта касания.
    pub stack_levels_at_arm: u32,
    /// Расстояние завала на кадре взвода, bps (Г-98): от первой до последней плотности того же
    /// окна и правила, что `stack_levels_at_arm`, по цене уровня; одна плотность (или ни одной) — 0.
    /// Кэш подходов до TK-206 читается нулём.
    pub stack_span_bps_at_arm: i64,
    /// Прошлых рождений уровня на этой цене и стороне в окне `repeat_window_ms` (Г-136/137 П-17):
    /// считается при рождении уровня (`TouchRecord::repeat_count`), к взводу известен — без заглядывания.
    /// Кэш подходов до TK-279 читается нулём.
    pub repeat_count_at_arm: u32,
    /// Лоты впереди уровня к взводу (T-28): то же правило, что
    /// `TouchRecord::frontrun_lots` (В-45, кадр не позже секунды до), от метки
    /// взвода. На взводе цена ещё в полосе от стены — это всё, что стоит между
    /// стеной и ценой, больше фронтрана касания.
    pub frontrun_lots_at_arm: i64,
    /// Признаки П-08 (TK-012) на кадре взвода; `None` — кэш подходов до TK-012
    /// (колонок нет), трекер пишет всегда `Some`.
    pub p08: Option<ArmP08>,
    /// Признаки R1 (TK-025) на кадре взвода, у подходов любой причины конца; `None` — трекер без
    /// `--r1-cols`, кэш без колонок R1 или уровень взведён и умер в бид-проходе того же кадра.
    pub r1: Option<Box<crate::lob::r1::ArmR1>>,
    /// Кадр начала касания, если подход кончился касанием.
    pub touch_start_ms: Option<i64>,
    /// Кадр снятия подхода (касание, смерть уровня или уход цены).
    pub disarm_ms: i64,
    /// Чем подход кончился.
    pub disarm_reason: ApproachEnd,
}

