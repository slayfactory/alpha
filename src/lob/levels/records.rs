/// Сколько первых наблюдений стороны берёт `ArmP08::depth_behind50_lots` —
/// глубина записи `.50` (В-106), чтобы дни `ob200` значили то же.
pub const DEPTH50_LEVELS: usize = 50;

/// Слотов в секундном кольце Г-55 (`EatRing`) — окно 60 с (П-08 §12 п. 5).
pub(super) const EAT_RING_S: usize = 60;

/// Кольцо Г-55 уровня: 60 слотов по секунде — сумма сделок по цене стены и
/// наибольший видимый размер. Слот секунды `t` — `t mod 60`; `sec` — самая
/// поздняя секунда, до которой кольцо продвинуто. Продвижение обнуляет
/// пропущенные секунды (не больше 60 — дальше всё кольцо): сделок в них ноль,
/// размер — последний видимый (он и стоял всё это время). Кучи нет.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct EatRing {
    pub(super) sec: i64,
    pub(super) lots: [i64; EAT_RING_S],
    pub(super) max: [i64; EAT_RING_S],
}

impl EatRing {
    /// Кольцо уровня, родившегося в секунду `sec` с размером `size`: секунды
    /// до рождения — ноль сделок и ноль размера.
    pub(super) fn new(sec: i64, size: i64) -> Self {
        let mut r = Self {
            sec,
            lots: [0; EAT_RING_S],
            max: [0; EAT_RING_S],
        };
        r.max[Self::slot(sec)] = size;
        r
    }

    pub(super) fn slot(sec: i64) -> usize {
        sec.rem_euclid(EAT_RING_S as i64) as usize
    }

    /// Слот секунды `sec` после продвижения к ней (`visible` — размер,
    /// видимый в пропущенных секундах); `None` — секунда старше окна.
    pub(super) fn slot_at(&mut self, sec: i64, visible: i64) -> Option<usize> {
        if sec > self.sec {
            let n = sec.saturating_sub(self.sec).min(EAT_RING_S as i64);
            for k in 0..n {
                let i = Self::slot(sec - k);
                self.lots[i] = 0;
                self.max[i] = visible;
            }
            self.sec = sec;
        }
        (self.sec.saturating_sub(sec) < EAT_RING_S as i64).then(|| Self::slot(sec))
    }

    pub(super) fn add_trade(&mut self, sec: i64, lots: i64, visible: i64) {
        if let Some(i) = self.slot_at(sec, visible) {
            self.lots[i] = self.lots[i].saturating_add(lots);
        }
    }

    pub(super) fn observe_size(&mut self, sec: i64, size: i64, visible: i64) {
        if let Some(i) = self.slot_at(sec, visible) {
            self.max[i] = self.max[i].max(size);
        }
    }

    /// `(сделки, наибольший размер)` за секунды `[sec − 59, sec]`, известные
    /// кольцу (не позже `self.sec` и не старше окна).
    pub(super) fn window(&self, sec: i64) -> (i64, i64) {
        let mut lots = 0i64;
        let mut max = 0i64;
        for k in 0..EAT_RING_S as i64 {
            let t = sec - k;
            if t <= self.sec && self.sec - t < EAT_RING_S as i64 {
                let i = Self::slot(t);
                lots = lots.saturating_add(self.lots[i]);
                max = max.max(self.max[i]);
            }
        }
        (lots, max)
    }
}

impl ApproachRecord {
    /// Возраст уровня на момент взвода, мс (`touch_record.age_ms` подхода).
    pub fn age_ms(&self) -> i64 {
        self.arm_ms - self.level_birth_ms
    }

    /// Сколько подход жил: от взвода до снятия, мс.
    pub fn duration_ms(&self) -> i64 {
        self.disarm_ms - self.arm_ms
    }
}

/// Потолок счётчика `round_zeros`: «3+» — практики называют круглым и
/// `1.100`, и `1111`, глубже трёх нулей различать нечего (§2 находок).
pub const ROUND_ZEROS_CAP: u8 = 3;

/// Число нулей в конце десятичной записи тика, не больше `ROUND_ZEROS_CAP`:
/// `100 → 2`, `1010 → 1`, `1234 → 0`, `10_000 → 3`. Ноль нулей не имеет —
/// тика ноль у цены не бывает, но арифметика тотальна. Знак не читается.
pub fn round_zeros(price_tick: i64) -> u8 {
    let mut n = price_tick.unsigned_abs();
    let mut zeros = 0u8;
    while n != 0 && n.is_multiple_of(10) && zeros < ROUND_ZEROS_CAP {
        n /= 10;
        zeros += 1;
    }
    zeros
}

/// Сколько времени до касания берётся фронтран (В-45): секунда —
/// `HORIZONS_MS[1]`, не новое число. Это же — шаг слота выборки.
pub const FRONTRUN_BACK_MS: i64 = HORIZONS_MS[1];

/// Базисных пунктов в единице — определение bps, не назначенное число.
pub(super) const BPS_PER_UNIT: i128 = 10_000;

/// Окно «завала» в тиках от цены уровня: `price_tick × DISTANCE_MAX_BPS /
/// 10 000`, целочисленно вниз (В-45). У дешёвого в тиках инструмента
/// (цена < 400 тиков) окно — ноль тиков: в «завале» только сам уровень.
/// Считается один раз на старте касания; отрицательного тика у цены нет,
/// модуль — чтобы арифметика была тотальна.
pub fn stack_window_ticks(price_tick: i64) -> i64 {
    let w = i128::from(price_tick.unsigned_abs()) * i128::from(DISTANCE_MAX_BPS) / BPS_PER_UNIT;
    i64::try_from(w).unwrap_or(i64::MAX)
}

/// Слот выборки фронтрана (В-45): наблюдения уровня за один шаг
/// `FRONTRUN_BACK_MS` от первого наблюдения слота — метка и лоты впереди
/// уровня на первом и на последнем из них. Два слота на уровень —
/// «старый» и «новый» — вместо хранения всех кадров секунды.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct FrontrunSlot {
    pub(super) start_ms: i64,
    pub(super) first_lots: i64,
    /// Цена **ближайшего** уровня с ненулевым размером строго лучше нашего,
    /// на том же наблюдении, что `first_lots` (B2, 2026-09-17). Именно она —
    /// «первый фронтранер»: вход от фронтрана (спека §2) ставится на его цену,
    /// а не на «лучшую из всех» — иначе вход уезжал бы к середине.
    pub(super) first_tick: Option<i64>,
    pub(super) last_ms: i64,
    pub(super) last_lots: i64,
    pub(super) last_tick: Option<i64>,
}

impl FrontrunSlot {
    pub(super) fn new(ts_ms: i64, lots: i64, tick: Option<i64>) -> Self {
        Self {
            start_ms: ts_ms,
            first_lots: lots,
            first_tick: tick,
            last_ms: ts_ms,
            last_lots: lots,
            last_tick: tick,
        }
    }
}
