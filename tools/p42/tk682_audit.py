HEAD = ["№", "Признак", "Настоящая группа", "То же, что №", "Связан с №", "Конфликт / зависимость", "Вердикт", "Окно 5–60 мин"]


def nums(cell):
    return [] if cell.strip() in ("", "—") else [int(x) for x in cell.split(",")]


def rows():
    out = {}
    for line in ROWS.strip().splitlines():
        p = [x.strip() for x in line.split("|")]
        assert len(p) == 8, line
        n = int(p[0])
        assert n not in out, f"№ {n} повторяется"
        assert p[5].split(":")[0].split(" в ")[0] in ("оставить", "убрать", "слить"), line
        assert p[6] in ("да", "нет", "—"), line
        out[n] = dict(n=n, group=p[1], same=nums(p[2]), rel=nums(p[3]), conf=p[4], verdict=p[5], fit=p[6], st=p[7])
    return out


def check(R, feats):
    # строки, добавленные на страницу после описи (№ > 251), в описи не обязательны
    assert sorted(R) == list(range(1, len(R) + 1)) and set(R) <= set(feats), "номера описи не совпадают с ml_features.json"
    for r in R.values():
        for k in r["same"] + r["rel"]:
            assert k in R and k != r["n"], f"№ {r['n']}: ссылка на № {k}"
        assert not set(r["same"]) & set(r["rel"]), f"№ {r['n']}: номер и в «то же», и в «связан»"
        for k in r["same"]:
            assert r["n"] in R[k]["same"], f"№ {r['n']} = № {k}, но у № {k} обратной ссылки нет"
        assert (r["verdict"] == "оставить") or r["st"], f"№ {r['n']}: вердикт без статуса для страницы"


def main():
    data = json.load(open(FEATURES, encoding="utf-8"))
    feats = {f["n"]: f for s in data["sets"] for g in s["groups"] for f in g["features"]}
    R = rows()
    check(R, feats)
    if "--check" in sys.argv:
        print("ok", len(R))
        return
    link = lambda xs: ", ".join(str(x) for x in xs) or "—"
    md = ["# П-42: опись связей признаков № 1–251 (22.11.2026, TK-682)", "",
          "| " + " | ".join(HEAD) + " |", "|" + "---|" * len(HEAD)]
    for n in sorted(R):
        r = R[n]
        md.append(f"| {n} | `{feats[n]['name']}` | {r['group']} | {link(r['same'])} | {link(r['rel'])} | {r['conf']} | {r['verdict']} | {r['fit']} |")
    open(OUT_MD, "w", encoding="utf-8", newline="\n").write("\n".join(md) + "\n")
    for n, f in feats.items():
        if n not in R:
            continue
        r = R[n]
        f.pop("rel", None)
        f.pop("st", None)
        rel = sorted(set(r["same"] + r["rel"]))
        if rel:
            f["rel"] = rel
        if r["st"]:
            f["st"] = r["st"]
    open(FEATURES, "w", encoding="utf-8", newline="\n").write(json.dumps(data, ensure_ascii=False, indent=1))
    v = [r["verdict"].split(":")[0].split(" в ")[0] for r in R.values()]
    print("строк", len(R), {k: v.count(k) for k in ("оставить", "слить", "убрать")})


