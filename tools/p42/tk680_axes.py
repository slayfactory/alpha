def base_patch(side):
    return dict(ax.cell_assign(side, {})[0])


def make_cell(side, axis, label, patch, filt_sem=None):
    """Клетка единички: patch — заплатка оси поверх базы стороны (со стопом базы); filt_sem — (столбец, знак, порог) или None."""
    p = base_patch(side)
    p.update(patch)
    filt = [(axis, label)] if filt_sem else []
    ck = ax.canon(ax.BASE_LINE(side) + (" " + ax.patch_str(p) if p else ""), [filt_sem] if filt_sem else [])
    return dict(ckey=ck, cid=ax.cell_id(p, filt), patch=p, filt=[list(x) for x in filt], sig=[list(x) for x in ax.sigkey(p)], axis=axis, label=label)


