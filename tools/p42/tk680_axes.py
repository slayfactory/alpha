OTHER_DIR = {"tpm60": "ge", "cons60": "ge", "n24": "le"}


def column_list(coverage_cols):
    """[(имя покрытия, источник parquet | (числитель, знаменатель), направления)] — все столбцы покрытия, кроме COL_SKIP."""
    if SET == "hist":
        return [(c, c, ("le", "ge")) for c in HIST_COLS]
    if SET in ("grid", "new"):
        return []
    if SET == "ctx":
        return [(c, c, ("le",)) for c in CTX_COLS]
    if SET == "t681":
        return [(c, c, ("le", "ge")) for c in FAST_NAMES]
    out = []
    for c in coverage_cols:
        if c in COL_SKIP or horizon_skip(c):
            continue
        out.append((c, COL_MAP.get(c, c), (OTHER_DIR[c],) if c in OTHER_DIR else ("le", "ge")))
    return out


def base_patch(side):
    return dict(ax.cell_assign(side, {})[0])


def make_cell(side, axis, label, patch, filt_sem=None):
    """Клетка единички: patch — заплатка оси поверх базы стороны (со стопом базы); filt_sem — (столбец, знак, порог) или None."""
    p = base_patch(side)
    p.update(patch)
    filt = [(axis, label)] if filt_sem else []
    ck = ax.canon(ax.BASE_LINE(side) + (" " + ax.patch_str(p) if p else ""), [filt_sem] if filt_sem else [])
    return dict(ckey=ck, cid=ax.cell_id(p, filt), patch=p, filt=[list(x) for x in filt], sig=[list(x) for x in ax.sigkey(p)], axis=axis, label=label)


