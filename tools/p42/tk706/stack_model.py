#!/usr/bin/env python3
"""TK-706 §5: модель стека рычагов e (ход по срезу), B (память исходов), A (пучок) поверх v1-lto.
Доли ЦП на v1 (H1, perf): S — обвязка хода (next_tick 20,3 + run_tick_xb 14,1), W — on_trade + fill_takes (20,6 + 8,9), R — остальное.
Формула: итог = (S − e)/G·(1 − r) + W/G + R;  e — выигрыш рычага e, G — число одинаковых ходов на один ход после памяти исходов,
r — доля оставшейся обвязки, которую снимает пучок.  Боевая смесь: доли ходов × k (фаза 2 = 78,2 % стены × доля ходов 72,6 % = 56,8 % против 63,9 % на H1)."""
def total(S, W, R, e, G, r):
    return (S - e) / G * (1 - r) + W / G + R

H = dict(S=0.344, W=0.295, R=0.361)
k = 0.568 / 0.639
B = dict(S=H['S'] * k, W=H['W'] * k, R=1 - (H['S'] + H['W']) * k)
SCEN = [('консервативно', 0.08, 1.0, 0.5), ('ожидаемо', 0.11, 2.0, 0.5), ('верхняя граница', 0.15, 4.9, 0.9)]
for name, P, lto, kk in (('H1', H, 0.765, 1.0), ('боевая смесь', B, 0.79, k)):
    for n, e, G, r in SCEN:
        t = total(P['S'], P['W'], P['R'], e * kk, G, r)
        print(f'{name:13s} {n:15s} v1=1: {t:.3f} (×{1 / t:.2f} к v1); к боевому `l`: {t * lto:.3f} (×{1 / (t * lto):.2f})')
