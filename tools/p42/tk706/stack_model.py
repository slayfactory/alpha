#!/usr/bin/env python3
"""TK-706 §5 (v2, после замечаний критика M1–M5): стена партии при занятом хосте (стена ∝ ЦП), по классам вызовов, в часах на 100 ч стены.
Измерено: LTO (a) по классам, G по тикам (ws-measure2, H1).  Допущения (названы в doc §5.3): w_c — доля ЦП в ходах; G одинаково для классов;
S/(S+W) = 0,5 (профиль v1); память исходов даёт ходы / G; пучок снимает долю r оставшейся обвязки S.  e (ход по срезу) в стек не входит — нет прототипа."""
CLASS = {  # стена класса за 3 ч боевых логов (с), доля фазы 2 в стене, доля ходов в ЦП (H1: 0,589 при фазе 2 = 88 %), отношение ЦП LTO / база (попадание, промах)
    'тяжёлый': dict(wall=3457, ph2=0.805, lto=(0.765, 0.759)),
    'средний': dict(wall=2463, ph2=0.760, lto=(0.838, 0.942)),
    'лёгкий': dict(wall=346, ph2=0.706, lto=(0.984, 0.876)),
}
W_H1, PH2_H1 = 0.589, 0.88
G = 1.98
HIT = 0.7  # доля попаданий кэша сигналов (боевые вызовы)
tot = sum(c['wall'] for c in CLASS.values())
def walk(c): return W_H1 * c['ph2'] / PH2_H1
def lto(c): return HIT * c['lto'][0] + (1 - HIT) * c['lto'][1]
def memo(c, g=G, r=0.0):
    w = walk(c)
    return 1 - w * (1 - 1 / g) - w * 0.5 / g * r
rows = [('a: LTO (измерено)', 0.0, None, 1.0), ('a + память исходов (G измерено)', 0.0, G, 1.0),
        ('a + память + пучок r = 0,5', 0.5, G, 1.0), ('a + память + пучок r = 0,9', 0.9, G, 1.0)]
for name, r, g, _ in rows:
    parts = []
    for k, c in CLASS.items():
        m = 1.0 if g is None else memo(c, g, r)
        parts.append(c['wall'] * lto(c) * m)
    t = sum(parts) / tot
    print(f'{name:36s} стена партии {100 * t:5.1f} ч из 100 (×{1 / t:.2f})  по классам: ' + ' '.join(f'{p / c["wall"]:.3f}' for p, c in zip(parts, CLASS.values())))
miss_extra = (0.084 / 0.3) * 0.7  # фаза 1 = 8,4 % стены при 30 % промахов; все промахи → 28 %; добавка ≈ 19,6 % стены партии, один раз на подмену
print(f'подмена бинаря без алиаса: +{100 * miss_extra:.1f} ч на 100 ч стены один раз; с алиасом (рычаг i): 0')
